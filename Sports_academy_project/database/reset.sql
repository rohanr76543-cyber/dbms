DROP DATABASE IF EXISTS sports_academy;
CREATE DATABASE sports_academy;
USE sports_academy;

CREATE TABLE TEAMS (
  TEAM_ID INT AUTO_INCREMENT PRIMARY KEY,
  TEAM_NAME VARCHAR(100) NOT NULL,
  COACH_NAME VARCHAR(100) NOT NULL,
  HOME_GROUND VARCHAR(100) NOT NULL
);

CREATE TABLE COACH (
  COACH_ID INT AUTO_INCREMENT PRIMARY KEY,
  COACH_NAME VARCHAR(100) NOT NULL,
  EXPERIENCE INT NOT NULL,
  COACH_AGE INT NOT NULL,
  TEAM_ID INT NOT NULL,
  CONSTRAINT fk_coach_team
    FOREIGN KEY (TEAM_ID) REFERENCES TEAMS(TEAM_ID)
    ON UPDATE CASCADE
    ON DELETE RESTRICT
);

CREATE TABLE PLAYERS (
  PLY_ID INT AUTO_INCREMENT PRIMARY KEY,
  PLY_NAME VARCHAR(100) NOT NULL,
  POSITION VARCHAR(60) NOT NULL,
  TEAM_ID INT NOT NULL,
  CONSTRAINT fk_players_team
    FOREIGN KEY (TEAM_ID) REFERENCES TEAMS(TEAM_ID)
    ON UPDATE CASCADE
    ON DELETE RESTRICT
);

CREATE TABLE MATCHS (
  MATCH_ID INT AUTO_INCREMENT PRIMARY KEY,
  DATE DATE NOT NULL,
  GROUND VARCHAR(100) NOT NULL,
  HOME_TEAM_ID INT NOT NULL,
  AWAY_TEAM_ID INT NOT NULL,
  CONSTRAINT fk_match_home_team
    FOREIGN KEY (HOME_TEAM_ID) REFERENCES TEAMS(TEAM_ID)
    ON UPDATE CASCADE
    ON DELETE RESTRICT,
  CONSTRAINT fk_match_away_team
    FOREIGN KEY (AWAY_TEAM_ID) REFERENCES TEAMS(TEAM_ID)
    ON UPDATE CASCADE
    ON DELETE RESTRICT
);

CREATE TABLE SCORE (
  MATCH_ID INT PRIMARY KEY,
  HOME_SCORE INT NOT NULL,
  AWAY_SCORE INT NOT NULL,
  WIN_TEAM VARCHAR(100) NOT NULL,
  CONSTRAINT fk_score_match
    FOREIGN KEY (MATCH_ID) REFERENCES MATCHS(MATCH_ID)
    ON UPDATE CASCADE
    ON DELETE RESTRICT
);
